/** localStorage that never throws (private mode, sandboxed previews). */
export const store = {
  get(k) { try { return localStorage.getItem(k); } catch { return null; } },
  set(k, v) { try { localStorage.setItem(k, v); } catch { /* private mode / sandbox */ } },
  del(k) { try { localStorage.removeItem(k); } catch { /* private mode / sandbox */ } },
};

/** Only http(s) links ever reach an href. */
export const safeUrl = (u) => (typeof u === 'string' && /^https?:\/\//i.test(u) ? u : '#');

let toastTimer;
/** Short message at the top of the screen, with an optional button (Undo by default: showToast(msg, fn, 'View')). */
export function showToast(message, onAction, actionLabel = 'Undo', ms = 4500) {
  const t = $('#toast');
  // Never pass null to replaceChildren(): it would show the word "null".
  t.replaceChildren(h('span', {}, message), ...(onAction ? [h('button', { type: 'button', onclick: () => { t.hidden = true; onAction(); } }, actionLabel)] : []));
  t.hidden = false;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => (t.hidden = true), ms);
}
