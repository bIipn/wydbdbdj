// DOM helpers shared by every screen. Strings always become text nodes, never HTML.

export const $ = (sel, root = document) => root.querySelector(sel);
export const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];

/**
 * Tiny element builder: h('button', { class: 'cta', onclick }, 'Save').
 * Props: class, on<event> functions, anything else becomes an attribute (true → present, false/null → absent).
 * Children: strings / numbers (text nodes), Nodes, arrays (flattened), null / false (skipped).
 */
export function h(tag, props = {}, ...children) {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(props || {})) {
    if (v == null || v === false) continue;
    if (k === 'class') el.className = v;
    else if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2), v);
    else el.setAttribute(k, v === true ? '' : String(v));
  }
  for (const c of children.flat(Infinity)) {
    if (c == null || c === false) continue;
    el.append(c instanceof Node ? c : document.createTextNode(String(c)));
  }
  return el;
}

/** Static, trusted SVG markup from ICONS only (never user data). */
export function icon(svg) {
  const span = document.createElement('span');
  span.innerHTML = svg;
  return span.firstElementChild;
}

